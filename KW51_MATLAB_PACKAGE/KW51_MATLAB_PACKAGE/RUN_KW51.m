% RUN_KW51 Main entry point: raw train archives -> analysis -> tables -> plots.
% Put both January ZIPs in input/ or select them when prompted. The bridge
% model and geometry are bundled under reference/ and loaded automatically.
packageRoot=fileparts(mfilename('fullpath'));
addpath(packageRoot,fullfile(packageRoot,'src'));
cfg=KW51_CONFIG(packageRoot);
for k=1:2
    if ~isfile(cfg.archives{k})
        [name,folder]=uigetfile('*.zip',sprintf('Select January traindata part %d',k));
        if isequal(name,0), error('KW51:Cancelled','Archive selection cancelled.'); end
        cfg.archives{k}=fullfile(folder,name);
    end
end
outputs=kw51_run_analysis(cfg.archives{1},cfg.archives{2}, ...
    'OutputRoot',cfg.outputRoot, ...
    'FEReferenceFile',fullfile(packageRoot,'reference','base_and_all_gauge_calibration.mat'), ...
    'CandidateFile',fullfile(packageRoot,'reference','candidate_regions.csv'), ...
    'NumberTrials',cfg.numberTrials,'NumberBootstrap',cfg.numberBootstrap, ...
    'NumberBootstrapExtended',cfg.numberBootstrapExtended, ...
    'PassageWindows',cfg.passageWindows,'RandomSeed',cfg.randomSeed, ...
    'MinimumJointRate',cfg.minimumJointRate, ...
    'RebuildRecords',cfg.rebuild,'RebuildFE',cfg.rebuild, ...
    'RebuildFeatures',cfg.rebuild,'RebuildTrials',cfg.rebuild);
copyfile(fullfile(packageRoot,'reference','strain_sensor_locations.csv'), ...
    fullfile(outputs.dataDirectory,'strain_sensor_locations.csv'),'f');
PRINT_KW51_RESULTS(cfg.outputRoot,cfg.plotAllLocations);
fprintf('\nTables: %s\nFigures: %s\n',outputs.dataDirectory,fullfile(cfg.outputRoot,'figures'));
